"""Collect every number reported in the paper from the files in results/ into results/paper_numbers.md.

Usage:  python paper_numbers.py --results results
Run after run_all.py, the sensitivity runs and alerts.py (see README). Each line gives the statement in the
paper, the value computed here and the file it comes from, so the paper can be checked against the outputs.
"""
import argparse
import os

import numpy as np
import pandas as pd


def pct(x, d=0):
    return f"{100 * x:.{d}f}%"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", default="results")
    a = ap.parse_args()
    T = os.path.join(a.results, "tables")
    S = os.path.join(a.results, "sensitivity")

    def tab(name, base=T, **kw):
        return pd.read_csv(os.path.join(base, name), **kw)

    L = ["# Numbers reported in the paper and where they come from", "",
         "Generated by `paper_numbers.py` from the files in `results/`. Section names refer to the paper.", ""]

    def row(section, statement, value, source):
        L.append(f"| {section} | {statement} | {value} | `{source}` |")

    L += ["| Section | Statement | Value | Source |", "| --- | --- | --- | --- |"]

    # Data and revisions
    rs = tab("rq1_revision_summary.csv", index_col=0)["value"]
    row("Methods", "snapshots", f"{int(float(rs['n_vintages']))} ({rs['first_vintage']} to {rs['last_vintage']})",
        "tables/rq1_revision_summary.csv")
    row("Methods", "later historical uploads / first publications",
        f"{int(float(rs['late_historical_uploads']))} / {int(float(rs['first_publications_after_first_snapshot']))}",
        "tables/rq1_revision_summary.csv")
    conv = tab("rq1_convergence_by_report_age.csv", index_col=0)
    row("Methods", "IQR of as-published / latest at week 8", f"{conv.loc[8, 'q25']:.3f}-{conv.loc[8, 'q75']:.3f}",
        "tables/rq1_convergence_by_report_age.csv")
    row("Results", "weeks with eight-week follow-up", f"{int(float(rs['weeks_with_8wk_followup']))}",
        "tables/rq1_revision_summary.csv")
    row("Results", "backfill > 10%", pct(float(rs["backfill_share_gt_10pct"])), "tables/rq1_revision_summary.csv")
    row("Results", "median backfill when revised", "+" + pct(float(rs["backfill_median_when_revised"])),
        "tables/rq1_revision_summary.csv")
    row("Results", "restatement > 10% (13 countries)", pct(float(rs["restatement_share_gt_10pct"])),
        "tables/rq1_revision_summary.csv")
    with open(os.path.join(a.results, "summary.md"), encoding="utf-8") as f:
        ctx = {ln.split(":")[0].strip("- ").strip(): ln.split(":", 1)[1].strip()
               for ln in f.read().splitlines() if ln.startswith("- restatement_gt10")}
    row("Results", "restatement > 10% without Greece and Latvia / in scored countries",
        f"{ctx.get('restatement_gt10_without_gr_lv')} / {ctx.get('restatement_gt10_included')}", "summary.md")
    rc = tab("rq1_revisions_by_country.csv", index_col=0)
    inc = ["Estonia", "Austria", "Germany", "Malta", "Spain", "Cyprus", "Luxembourg"]
    row("Results", "median first-report completeness",
        ", ".join(f"{c} {pct(rc.loc[c, 'first_over_stable_median'])}" for c in inc),
        "tables/rq1_revisions_by_country.csv")
    row("Discussion", "Estonia completeness IQR",
        f"{rc.loc['Estonia', 'first_over_stable_q25']:.2f}-{rc.loc['Estonia', 'first_over_stable_q75']:.2f}",
        "tables/rq1_revisions_by_country.csv")
    ir = tab("inclusion_rule.csv", index_col=0)
    row("Methods", "restatement shares deciding the 7%-34% threshold range",
        f"highest included {ir[ir.included].restatement_gt_10.max():.3f}, lowest excluded "
        f"{ir[ir.fail_restatement].restatement_gt_10.min():.3f}", "tables/inclusion_rule.csv")
    nt = tab("main_training_rows_by_origin.csv", index_col=0)
    row("Methods", "training pairs D (min-max) / A-C (min-max)",
        f"{int(nt.D_vintage_trained.min())}-{int(nt.D_vintage_trained.max())} / "
        f"{int(nt.A_retrospective.min())}-{int(nt.A_retrospective.max())}", "tables/main_training_rows_by_origin.csv")
    sc = tab("main_screened_training_pairs_by_origin.csv", index_col=0)
    row("Methods", "training pairs removed by the 50-fold screen (max per origin)",
        ", ".join(f"{c[0]} {int(sc[c].max())}" for c in sc.columns), "tables/main_screened_training_pairs_by_origin.csv")

    # Main gap
    g = tab("gap_by_arm_all_analyses.csv")
    gm = g[(g.analysis == "main")].set_index(["model", "h"])

    def exc(r, k):
        return f"{r[f'{k}_excess_pct']:+.0f}% ({r[f'{k}_lo']:.0f}-{r[f'{k}_hi']:.0f})"

    r1, r2 = gm.loc[("gbm", 1)], gm.loc[("gbm", 2)]
    row("Results / Table 1", "scored origins / one-week forecasts / two-week forecasts",
        f"{int(r1.n_origins)} / {int(r1.n_forecasts)} / {int(r2.n_forecasts)}", "tables/gap_by_arm_all_analyses.csv")
    for k, lab in (("A", "A"), ("B", "B"), ("C", "C"), ("D", "D")):
        row("Table 1", f"MAE {lab}, one week", f"{r1[f'MAE_{k}']:.3f}", "tables/gap_by_arm_all_analyses.csv")
    for k in ("B", "C", "D"):
        row("Table 1", f"excess {k} vs A, one week / two weeks", f"{exc(r1, k)} / {exc(r2, k)}",
            "tables/gap_by_arm_all_analyses.csv")
    for k in ("C", "D"):
        row("Table 1", f"gap closed by {k}",
            f"{r1[f'gap_closed_{k}_pct']:.0f}% ({r1[f'gap_closed_{k}_lo']:.0f}-{r1[f'gap_closed_{k}_hi']:.0f})",
            "tables/gap_by_arm_all_analyses.csv")
    bias = tab("main_bias_by_arm.csv").set_index(["model", "h"]).loc[("gbm", 1)]
    row("Table 1", "bias A / B / C / D", " / ".join(f"{bias[c]:+.2f}" for c in bias.index),
        "tables/main_bias_by_arm.csv")
    row("Abstract", "pooled real-time / retrospective MAE ratio", f"{r1.MAE_B / r1.MAE_A:.2f} "
        f"(origin bootstrap {1 + r1.B_lo / 100:.1f}-{1 + r1.B_hi / 100:.1f})", "tables/gap_by_arm_all_analyses.csv")
    cc = tab("main_country_cluster_bootstrap.csv").set_index("quantity")
    row("Abstract / Results", "pooled excess with countries resampled (95% CI)",
        f"{cc.loc['B_excess_pct', 'lo']:.0f}%-{cc.loc['B_excess_pct', 'hi']:.0f}% "
        f"(ratio {1 + cc.loc['B_excess_pct', 'lo'] / 100:.1f}-{1 + cc.loc['B_excess_pct', 'hi'] / 100:.1f})",
        "tables/main_country_cluster_bootstrap.csv")
    row("Results", "gap closed by C with countries resampled",
        f"{cc.loc['gap_closed_C_pct', 'lo']:.0f}%-{cc.loc['gap_closed_C_pct', 'hi']:.0f}%",
        "tables/main_country_cluster_bootstrap.csv")
    for m, lab in (("ridge", "ridge"), ("persistence", "persistence")):
        row("Results", f"excess B vs A, {lab}, one week", f"{gm.loc[(m, 1), 'B_excess_pct']:+.0f}%",
            "tables/gap_by_arm_all_analyses.csv")
    row("Results", "ridge: gap closed by C / D",
        f"{gm.loc[('ridge', 1), 'gap_closed_C_pct']:.0f}% / {gm.loc[('ridge', 1), 'gap_closed_D_pct']:.0f}%",
        "tables/gap_by_arm_all_analyses.csv")

    pc = tab("per_country_gbm_h1_all_analyses.csv")
    pm = pc[pc.analysis == "main"].set_index("countryname")
    for c in inc:
        r = pm.loc[c]
        ci = (f" ({r.ratio_B_lo:.2f}-{r.ratio_B_hi:.2f})" if bool(r.ci_reliable) else " (no CI, <20 origins)")
        row("Results / Figure 1b", f"{c}: error ratio B/A; C/A; D/A",
            f"{r.ratio_B:.2f}{ci}; {r.ratio_C:.2f}; {r.ratio_D:.2f}", "tables/per_country_gbm_h1_all_analyses.csv")
    row("Discussion", "Germany C/A (95% CI)",
        f"{pm.loc['Germany', 'ratio_C']:.2f} ({pm.loc['Germany', 'ratio_C_lo']:.2f}-{pm.loc['Germany', 'ratio_C_hi']:.2f})",
        "tables/per_country_gbm_h1_all_analyses.csv")
    gs = tab("main_gap_share_by_country.csv", index_col=0)["share"]
    row("Abstract / Results", "share of the pooled gap from Estonia and Austria",
        pct(gs["Estonia"] + gs["Austria"]), "tables/main_gap_share_by_country.csv")
    wo = tab("main_without_estonia_austria.csv", index_col=0)["value"]
    row("Results", "excess without Estonia and Austria",
        f"{float(wo['B_excess_pct']):+.0f}% ({float(wo['B_lo']):.0f}-{float(wo['B_hi']):.0f})",
        "tables/main_without_estonia_austria.csv")
    bc = tab("main_bias_by_country_gbm_h1.csv", index_col=0)
    row("Results", "real-time under-forecast (geometric mean)",
        ", ".join(f"{c} {pct(1 - np.exp(bc.loc[c, 'B_realtime']))}" for c in ["Estonia", "Austria", "Germany"]),
        "tables/main_bias_by_country_gbm_h1.csv")

    # Robustness
    def gb(analysis, frame=g):
        return frame[(frame.analysis == analysis) & (frame.model == "gbm") & (frame.h == 1)].iloc[0]

    lt = tab("gap_by_arm_latest_file_truth_all_analyses.csv")
    row("Results", "ages 65+: excess", exc(gb("age_65plus"), "B"), "tables/gap_by_arm_all_analyses.csv")
    r04 = gb("age_0to4")
    row("Results", "ages 0-4: excess; gap closed by C", f"{exc(r04, 'B')}; {r04.gap_closed_C_pct:.0f}%",
        "tables/gap_by_arm_all_analyses.csv")
    row("Results", "12-week truth: excess", exc(gb("truth_12wk"), "B"), "tables/gap_by_arm_all_analyses.csv")
    row("Results", "latest file as truth: excess", exc(gb("main", lt), "B"),
        "tables/gap_by_arm_latest_file_truth_all_analyses.csv")
    lo = tab("main_leave_one_country_out.csv").set_index("left_out")
    row("Results", "without Estonia (leave one out)", f"{lo.loc['Estonia', 'B_excess_pct']:+.0f}%",
        "tables/main_leave_one_country_out.csv")
    r5 = gb("main", tab("gap_by_arm_all_analyses.csv", base=os.path.join(S, "restatement_5pct", "tables")))
    row("Results", "5% restatement threshold (Cyprus excluded)", exc(r5, "B"),
        "sensitivity/restatement_5pct/tables/gap_by_arm_all_analyses.csv")
    ra = gb("all_series")
    row("Results / Discussion", "11 series, week-8 truth", exc(ra, "B"), "tables/gap_by_arm_all_analyses.csv")
    below = pc[(pc.analysis == "all_series") & (pc.ratio_B_over_A < 1)].countryname.tolist()
    row("Results", "11 series: countries with B/A below 1", ", ".join(below), "tables/per_country_gbm_h1_all_analyses.csv")
    rla = gb("all_series", lt)
    row("Results", "11 series, latest-file truth: excess; gap closed by C",
        f"{exc(rla, 'B')}; {rla.gap_closed_C_pct:.0f}%", "tables/gap_by_arm_latest_file_truth_all_analyses.csv")
    rsb, rsbl = gb("with_scale_breaks"), gb("with_scale_breaks", lt)
    row("Results", "13 series with scale breaks: week-8 truth / latest-file truth",
        f"{rsb.B_excess_pct:+.0f}% / {rsbl.B_excess_pct:+.0f}%", "tables/gap_by_arm_all_analyses.csv")

    # Alerts
    al = tab("main_alerts.csv").set_index(["model", "h"]).loc[("gbm", 1)]
    row("Results", "high-activity weeks / scored forecasts", f"{int(al.events)} / {int(al.n)}", "tables/main_alerts.csv")
    for arm, lab in (("A_retrospective", "A"), ("B_realtime", "B"), ("C_realtime_corrected", "C"),
                     ("D_vintage_trained", "D")):
        row("Abstract / Results", f"alerts {lab}: sensitivity (95% CI); false-alert rate; AUROC",
            f"{pct(al[f'sens_{arm}'])} ({pct(al[f'sens_{arm}_lo'])}-{pct(al[f'sens_{arm}_hi'])}); "
            f"{pct(al[f'far_{arm}'])}; {al[f'auroc_{arm}']:.2f}", "tables/main_alerts.csv")
    ab = tab("main_alerts_by_country_gbm_h1.csv", index_col=0)
    ea = ab.loc[["Estonia", "Austria"]]
    row("Results", "alerts B caught in Estonia and Austria",
        f"{int(round((ea.sens_B * ea.events).sum()))} of {int(ea.events.sum())}", "tables/main_alerts_by_country_gbm_h1.csv")
    aw = tab("main_alerts_without_estonia_austria.csv", index_col=0)["value"].astype(float)
    row("Abstract / Results", "alerts without Estonia and Austria: sensitivity A -> B; difference (95% CI)",
        f"{pct(aw['sens_A_retrospective'])} -> {pct(aw['sens_B_realtime'])}; {100 * aw['A_minus_B']:.0f} points "
        f"({100 * aw['A_minus_B_lo']:.0f}-{100 * aw['A_minus_B_hi']:.0f})", "tables/main_alerts_without_estonia_austria.csv")
    row("Abstract", "share of lost alert sensitivity recovered by C",
        pct((al.sens_C_realtime_corrected - al.sens_B_realtime) / (al.sens_A_retrospective - al.sens_B_realtime)),
        "tables/main_alerts.csv")
    for q in (50, 90):
        base = os.path.join(S, f"alerts_q{q}", "tables")
        aq = tab("main_alerts.csv", base=base).set_index(["model", "h"]).loc[("gbm", 1)]
        wq = tab("main_alerts_without_estonia_austria.csv", base=base, index_col=0)["value"].astype(float)
        row("Results", f"{q}th-percentile threshold: drop in sensitivity overall / without Estonia and Austria",
            f"{100 * aq.sens_A_minus_B:.0f} / {100 * wq['A_minus_B']:.0f} points",
            f"sensitivity/alerts_q{q}/tables/main_alerts*.csv")

    # Horizon audit
    hc = tab("horizon_audit_counts.csv", index_col=0)
    for h in (1, 2):
        r = hc.loc[h]
        n = r.sum()
        row("Methods", f"{h}-week targets: current / past / future week at the forecast date",
            f"{pct(r.get('current', 0) / n)} / {pct(r.get('past', 0) / n)} / {pct(r.get('future', 0) / n)} (n={n})",
            "tables/horizon_audit_counts.csv")
    hg = tab("horizon_audit_gap.csv")
    fg = hg[(hg.subset == "future only") & (hg.h == 2)].iloc[0]
    row("Results", "future targets only (two weeks ahead): forecasts; excess",
        f"{int(fg.n_forecasts)}; {exc(fg, 'B')}", "tables/horizon_audit_gap.csv")
    ha = tab("horizon_audit_alerts.csv")
    fa = ha[(ha.subset == "future only") & (ha.h == 2)].iloc[0]
    row("Results", "future targets only: alert sensitivity A -> B; difference (95% CI)",
        f"{pct(fa.sens_A_retrospective)} -> {pct(fa.sens_B_realtime)}; {100 * fa.A_minus_B:.0f} points "
        f"({100 * fa.A_minus_B_lo:.0f}-{100 * fa.A_minus_B_hi:.0f})", "tables/horizon_audit_alerts.csv")

    with open(os.path.join(a.results, "paper_numbers.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
